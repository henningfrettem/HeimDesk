-- HeimDesk: Supabase setup. Paste the whole file into the SQL Editor and run
-- it. It's safe to re-run, and re-running it is also how an existing project
-- picks up changes, including the move from the app's old "todo" schema.
--
-- It runs as one transaction: if any statement fails, nothing has changed.
--
-- Everything lives in a dedicated "heimdesk" schema, so this instance can be
-- shared with other small projects. To remove the app entirely:
--   drop schema heimdesk cascade;
--
-- AFTER RUNNING THIS: Settings -> API -> Exposed schemas must list
-- "heimdesk" (and no longer "todo"). PostgREST only serves schemas listed
-- there; without it every request fails.
--
-- Then run supabase/tests/rls_isolation.sql to check that one user can't
-- reach another's data.

begin;

-- ---------- From the old name ----------
-- The app used to be called Todo, and lived in a "todo" schema. Renaming the
-- schema keeps every row, id, index, trigger, policy and grant, and its tables
-- stay in the realtime publication; only the name changes. It happens only
-- when the old schema is unmistakably this app's and "heimdesk" doesn't exist.

do $$
begin
  if to_regnamespace('heimdesk') is null
     and to_regclass('todo.folders') is not null
     and to_regclass('todo.categories') is not null
     and to_regclass('todo.tasks') is not null then
    alter schema todo rename to heimdesk;
    raise notice 'Renamed schema todo to heimdesk.';
  end if;
end $$;

create schema if not exists heimdesk;

-- ---------- Tables ----------
-- Ids are generated by the client (crypto.randomUUID) and reused verbatim here,
-- so a save is a plain upsert with no id mapping to maintain.
--
-- Every row belongs to one user, and a row points at its parent through the
-- owner as well: (parent_id, user_id) references parent (id, user_id). So no
-- one can hang a row off someone else's, even knowing its id. (See "Links
-- locked to their owner", below, for tables made before this.)

create table if not exists heimdesk.folders (
  id          uuid primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name        text not null,
  position    integer not null default 0,
  updated_at  timestamptz not null default now(),
  constraint folders_id_user_key unique (id, user_id)
);

create table if not exists heimdesk.categories (
  id          uuid primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  folder_id   uuid not null,
  name        text not null,
  position    integer not null default 0,
  -- Blurs card text on the board until revealed. A display concession, not a
  -- security boundary: the rows are plain text here and in any export.
  private     boolean not null default false,
  updated_at  timestamptz not null default now(),
  constraint categories_id_user_key unique (id, user_id),
  constraint categories_folder_owner_fkey foreign key (folder_id, user_id)
    references heimdesk.folders (id, user_id) on delete cascade
);

create table if not exists heimdesk.tasks (
  id            uuid primary key,
  user_id       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  folder_id     uuid not null,
  category_id   uuid not null,
  subject       text not null default '',
  description   text not null default '',
  completed     boolean not null default false,
  important     boolean not null default false,
  -- Blurred on the board; readable as soon as the card is opened.
  private       boolean not null default false,
  due_date      date,
  position      integer not null default 0,
  created_at    timestamptz not null default now(),
  completed_at  timestamptz,
  updated_at    timestamptz not null default now(),
  constraint tasks_id_user_key unique (id, user_id),
  constraint tasks_folder_owner_fkey foreign key (folder_id, user_id)
    references heimdesk.folders (id, user_id) on delete cascade,
  constraint tasks_category_owner_fkey foreign key (category_id, user_id)
    references heimdesk.categories (id, user_id) on delete cascade
);

-- ---------- Checklists ----------
-- A card with items is a checklist (a shopping list, say). Each item is a row
-- of its own so that ticking items on two devices at once merges item by item.

create table if not exists heimdesk.checklist_items (
  id          uuid primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  task_id     uuid not null,
  text        text not null default '',
  done        boolean not null default false,
  position    integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint checklist_items_task_owner_fkey foreign key (task_id, user_id)
    references heimdesk.tasks (id, user_id) on delete cascade
);

-- ---------- Notes ----------
-- The pane to the left of the board. Each folder has its own note categories;
-- a note is a heading plus a thread of timestamped entries, newest first.

create table if not exists heimdesk.note_categories (
  id          uuid primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  folder_id   uuid not null,
  name        text not null,
  position    integer not null default 0,
  -- Blurs the note titles in the pane until revealed, like a private column.
  private     boolean not null default false,
  updated_at  timestamptz not null default now(),
  constraint note_categories_id_user_key unique (id, user_id),
  constraint note_categories_folder_owner_fkey foreign key (folder_id, user_id)
    references heimdesk.folders (id, user_id) on delete cascade
);

create table if not exists heimdesk.notes (
  id           uuid primary key,
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,
  category_id  uuid not null,
  -- Required by the app, deliberately not by the database: a note that is
  -- still being written is saved before it has a heading, and a constraint
  -- here would turn that into lost text.
  title        text not null default '',
  private      boolean not null default false,
  archived     boolean not null default false,
  archived_at  timestamptz,
  position     integer not null default 0,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint notes_id_user_key unique (id, user_id),
  constraint notes_category_owner_fkey foreign key (category_id, user_id)
    references heimdesk.note_categories (id, user_id) on delete cascade
);

create table if not exists heimdesk.note_entries (
  id          uuid primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  note_id     uuid not null,
  -- A text entry's sanitised HTML. Images are <img data-sb="<file>">
  -- pointing into the todo-images bucket, never a URL: signed URLs expire.
  -- For a diagram or mind map (see kind, below), its drawing as JSON.
  body        text not null default '',
  position    integer not null default 0,
  -- The timestamp shown on the entry. Reordering never changes it.
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint note_entries_note_owner_fkey foreign key (note_id, user_id)
    references heimdesk.notes (id, user_id) on delete cascade
);

-- ---------- Later additions ----------
-- "create table if not exists" above is a no-op once the table exists, so
-- columns added after the first run need their own statement.

alter table heimdesk.categories add column if not exists private boolean not null default false;
alter table heimdesk.tasks      add column if not exists private boolean not null default false;
-- What an entry is: 'text', 'diagram' or 'mindmap'. Until this exists the app
-- still works, it just won't offer diagrams and mind maps.
alter table heimdesk.note_entries add column if not exists kind text not null default 'text';

create index if not exists folders_user_pos    on heimdesk.folders    (user_id, position);
create index if not exists categories_fold_pos on heimdesk.categories (folder_id, position);
create index if not exists tasks_cat_pos       on heimdesk.tasks      (category_id, position);
create index if not exists tasks_user          on heimdesk.tasks      (user_id);
create index if not exists checklist_items_pos on heimdesk.checklist_items (task_id, position);
create index if not exists note_cats_fold_pos  on heimdesk.note_categories (folder_id, position);
create index if not exists notes_cat_pos       on heimdesk.notes           (category_id, position);
create index if not exists note_entries_pos    on heimdesk.note_entries    (note_id, position);

-- ---------- Links locked to their owner ----------
-- Tables made before the owner-locked links had plain foreign keys on the
-- parent's id alone. These add the owner-locked ones and drop the old ones.
-- Adding a key checks every existing row against it, so if any row pointed
-- at another user's, this stops here and the whole file changes nothing.

do $$
declare
  link record;
  old record;
begin
  -- Each parent needs (id, user_id) to be unique for a key to point at it.
  for link in select * from (values
    ('folders'), ('categories'), ('tasks'), ('note_categories'), ('notes')
  ) as t(tbl) loop
    if not exists (select 1 from pg_constraint
                   where conrelid = format('heimdesk.%I', link.tbl)::regclass
                     and conname = link.tbl || '_id_user_key') then
      execute format('alter table heimdesk.%I add constraint %I unique (id, user_id)',
                     link.tbl, link.tbl || '_id_user_key');
    end if;
  end loop;

  for link in select * from (values
    ('categories',      'folder_id',   'folders',         'categories_folder_owner_fkey'),
    ('tasks',           'folder_id',   'folders',         'tasks_folder_owner_fkey'),
    ('tasks',           'category_id', 'categories',      'tasks_category_owner_fkey'),
    ('checklist_items', 'task_id',     'tasks',           'checklist_items_task_owner_fkey'),
    ('note_categories', 'folder_id',   'folders',         'note_categories_folder_owner_fkey'),
    ('notes',           'category_id', 'note_categories', 'notes_category_owner_fkey'),
    ('note_entries',    'note_id',     'notes',           'note_entries_note_owner_fkey')
  ) as t(child, col, parent, name) loop
    if not exists (select 1 from pg_constraint
                   where conrelid = format('heimdesk.%I', link.child)::regclass
                     and conname = link.name) then
      execute format(
        'alter table heimdesk.%I add constraint %I foreign key (%I, user_id) references heimdesk.%I (id, user_id) on delete cascade',
        link.child, link.name, link.col, link.parent);
    end if;
    -- The old single-column key on the same column, whatever it was called.
    for old in
      select c.conname from pg_constraint c
      where c.contype = 'f'
        and c.conrelid = format('heimdesk.%I', link.child)::regclass
        and c.confrelid = format('heimdesk.%I', link.parent)::regclass
        and c.conkey = array[(select attnum from pg_attribute
                              where attrelid = c.conrelid and attname = link.col)]::int2[]
    loop
      execute format('alter table heimdesk.%I drop constraint %I', link.child, old.conname);
    end loop;
  end loop;
end $$;

-- ---------- updated_at ----------
-- Set server-side so a row's mtime can't be faked by a client with a skewed
-- clock. Useful later for deciding which side of a two-device edit is newer.

create or replace function heimdesk.touch_updated_at() returns trigger
  language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists folders_touch    on heimdesk.folders;
drop trigger if exists categories_touch on heimdesk.categories;
drop trigger if exists tasks_touch      on heimdesk.tasks;
drop trigger if exists note_categories_touch on heimdesk.note_categories;
drop trigger if exists notes_touch           on heimdesk.notes;
drop trigger if exists note_entries_touch    on heimdesk.note_entries;
drop trigger if exists checklist_items_touch on heimdesk.checklist_items;

create trigger folders_touch    before update on heimdesk.folders    for each row execute function heimdesk.touch_updated_at();
create trigger categories_touch before update on heimdesk.categories for each row execute function heimdesk.touch_updated_at();
create trigger tasks_touch      before update on heimdesk.tasks      for each row execute function heimdesk.touch_updated_at();
create trigger note_categories_touch before update on heimdesk.note_categories for each row execute function heimdesk.touch_updated_at();
create trigger notes_touch           before update on heimdesk.notes           for each row execute function heimdesk.touch_updated_at();
create trigger note_entries_touch    before update on heimdesk.note_entries    for each row execute function heimdesk.touch_updated_at();
create trigger checklist_items_touch before update on heimdesk.checklist_items for each row execute function heimdesk.touch_updated_at();

-- ---------- Grants ----------
-- Only signed-in users get anything, and only what the app does: read, add,
-- change and delete rows. Row-level security, below, then limits them to
-- their own rows. The signed-out role (anon) gets nothing at all, and nobody
-- gets truncate, which row-level security doesn't cover. Triggers run without
-- anyone needing execute on their function.

revoke all on schema heimdesk from public, anon;
revoke all on all tables    in schema heimdesk from public, anon, authenticated;
revoke all on all sequences in schema heimdesk from public, anon, authenticated;
revoke all on all routines  in schema heimdesk from public, anon, authenticated;

grant usage on schema heimdesk to authenticated, service_role;
grant select, insert, update, delete on all tables in schema heimdesk to authenticated;
grant all on all tables    in schema heimdesk to service_role;
grant all on all sequences in schema heimdesk to service_role;
grant all on all routines  in schema heimdesk to service_role;

-- The same for anything created here later.
alter default privileges in schema heimdesk revoke all on tables    from public, anon, authenticated;
alter default privileges in schema heimdesk revoke all on sequences from public, anon, authenticated;
alter default privileges in schema heimdesk revoke all on routines  from public, anon, authenticated;
alter default privileges in schema heimdesk grant select, insert, update, delete on tables to authenticated;
alter default privileges in schema heimdesk grant all on tables    to service_role;
alter default privileges in schema heimdesk grant all on sequences to service_role;
alter default privileges in schema heimdesk grant all on routines  to service_role;

-- ---------- Row Level Security ----------
-- The publishable key is public by design and lives in a public repo, so RLS is
-- the only thing protecting this data. Each table has one policy: a signed-in
-- user reads and writes their own rows, and can't make a row anyone else's.

alter table heimdesk.folders         enable row level security;
alter table heimdesk.categories      enable row level security;
alter table heimdesk.tasks           enable row level security;
alter table heimdesk.checklist_items enable row level security;
alter table heimdesk.note_categories enable row level security;
alter table heimdesk.notes           enable row level security;
alter table heimdesk.note_entries    enable row level security;

drop policy if exists folders_owner         on heimdesk.folders;
drop policy if exists categories_owner      on heimdesk.categories;
drop policy if exists tasks_owner           on heimdesk.tasks;
drop policy if exists checklist_items_owner on heimdesk.checklist_items;
drop policy if exists note_categories_owner on heimdesk.note_categories;
drop policy if exists notes_owner           on heimdesk.notes;
drop policy if exists note_entries_owner    on heimdesk.note_entries;

-- (select auth.uid()) rather than auth.uid(): evaluated once per query instead
-- of once per row, which is Supabase's advice for RLS performance.
create policy folders_owner         on heimdesk.folders         for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy categories_owner      on heimdesk.categories      for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy tasks_owner           on heimdesk.tasks           for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy checklist_items_owner on heimdesk.checklist_items for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy note_categories_owner on heimdesk.note_categories for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy notes_owner           on heimdesk.notes           for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy note_entries_owner    on heimdesk.note_entries    for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- ---------- Realtime ----------
-- The app listens for changes to these tables, so an edit on one device shows
-- on the others without a reload. The publication is shared with every other
-- project on this instance, hence the membership check.

do $$
declare t text;
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;
  foreach t in array array['folders', 'categories', 'tasks', 'checklist_items', 'note_categories', 'notes', 'note_entries'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'heimdesk' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table heimdesk.%I', t);
    end if;
  end loop;
end $$;

-- ---------- Storage bucket for pasted images ----------
-- Buckets are global to the instance, so the name is project-prefixed. It
-- keeps the app's old name: renaming a bucket means copying every file in it,
-- and the name is never shown. Private: files are reachable only through
-- short-lived signed URLs. Up to 10 MB a file, and only image types a browser
-- shows without running anything (no SVG, which can carry script). The app
-- checks the same before uploading; files already stored aren't affected.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
  values ('todo-images', 'todo-images', false, 10485760,
          array['image/png', 'image/jpeg', 'image/gif', 'image/webp'])
  on conflict (id) do update
    set public = false,
        file_size_limit = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types;

-- These policies live on the shared storage.objects table alongside every
-- other project's, hence the project-prefixed names. Each signed-in user can
-- only touch files under their own id, the path prefix the app uploads to.

drop policy if exists todo_images_select on storage.objects;
drop policy if exists todo_images_insert on storage.objects;
drop policy if exists todo_images_update on storage.objects;
drop policy if exists todo_images_delete on storage.objects;

create policy todo_images_select on storage.objects for select to authenticated
  using (bucket_id = 'todo-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy todo_images_insert on storage.objects for insert to authenticated
  with check (bucket_id = 'todo-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy todo_images_update on storage.objects for update to authenticated
  using (bucket_id = 'todo-images' and (storage.foldername(name))[1] = (select auth.uid())::text)
  with check (bucket_id = 'todo-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy todo_images_delete on storage.objects for delete to authenticated
  using (bucket_id = 'todo-images' and (storage.foldername(name))[1] = (select auth.uid())::text);

-- ---------- Check, then commit ----------
-- Nothing above should have touched a row. If the counts below look wrong,
-- or anything failed, the transaction is rolled back and nothing has changed.

do $$
declare
  t text;
  n bigint;
  report text := '';
begin
  foreach t in array array['folders', 'categories', 'tasks', 'checklist_items', 'note_categories', 'notes', 'note_entries'] loop
    if not (select relrowsecurity from pg_class where oid = format('heimdesk.%I', t)::regclass) then
      raise exception 'RLS is off on heimdesk.%', t;
    end if;
    if has_table_privilege('anon', format('heimdesk.%I', t), 'select') then
      raise exception 'anon can still read heimdesk.%', t;
    end if;
    execute format('select count(*) from heimdesk.%I', t) into n;
    report := report || format('%s %s, ', t, n);
  end loop;
  raise notice 'heimdesk rows: %', rtrim(report, ', ');
end $$;

notify pgrst, 'reload schema';

commit;

